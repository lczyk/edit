/// A text buffer for a text editor.
pub struct TextBuffer {
    buffer: GapBuffer,

    undo_stack: VecDeque<SemiRefCell<HistoryEntry>>,
    redo_stack: VecDeque<SemiRefCell<HistoryEntry>>,
    last_history_type: HistoryType,
    last_save_generation: u32,

    active_edit_group: Option<ActiveEditGroupInfo>,
    active_edit_line_info: Option<ActiveEditLineInfo>,
    active_edit_depth: i32,
    active_edit_off: usize,

    stats: TextBufferStatistics,
    cursor: Cursor,
    // When scrolling significant amounts of text away from the cursor,
    // rendering will naturally slow down proportionally to the distance.
    // To avoid this, we cache the cursor position for rendering.
    // Must be cleared on every edit or reflow.
    cursor_for_rendering: Option<Cursor>,
    /// Per-frame viewport row index. Rebuilt by `layout()`, consulted by
    /// `cursor_move_to_visual_internal` under word-wrap. See [`WrappedView`].
    wrapped_view: Option<WrappedView>,
    selection: Option<TextBufferSelection>,
    selection_generation: u32,
    search: Option<UnsafeCell<ActiveSearch>>,
    highlighter_cache: HighlighterCache,

    width: CoordType,
    margin_width: CoordType,
    margin_enabled: bool,
    word_wrap_column: CoordType,
    word_wrap_enabled: bool,
    tab_size: CoordType,
    indent_with_tabs: bool,
    line_highlight_enabled: bool,
    column_guides_enabled: bool,
    language: Option<&'static Language>,
    ruler: CoordType,
    newlines_are_crlf: bool,
    insert_final_newline: bool,
    overtype: bool,
    read_only: bool,

    /// Sticky x kept across vertical cursor motion so moving Down through a
    /// short line and then back up doesn't forget the original column.
    /// Updated by horizontal motion; preserved by vertical motion.
    preferred_column: CoordType,

    wants_cursor_visibility: bool,
    wants_scroll_delta_x: CoordType,
    wants_scroll_delta_y: CoordType,

    /// Indexed by logical line `y`. Empty means "no marks". May be shorter
    /// or longer than the current logical line count if a refresh is
    /// pending; out-of-range lookups return `GutterMark::None`.
    gutter_marks: Vec<GutterMark>,

    /// One row per `MINIMAP_SOURCE_ROWS_PER_CELL` source lines. Empty means
    /// the rail is hidden. `minimap_content_rows` records the source-line
    /// count the cells were built for; consumers use it to map viewport
    /// scroll into rail coordinates.
    minimap_cells: Vec<MinimapCell>,
    minimap_content_rows: u32,

    /// Most recent line-move event; **non-draining**. Set by
    /// `move_selected_lines`. Animators distinguish "already seen"
    /// from "fresh" via the companion [`pending_line_move_gen`]
    /// counter -- bumped on every set, monotonic across the
    /// buffer's lifetime.
    pending_line_move: Option<LineMoveEvent>,
    /// Monotonic generation that bumps whenever `pending_line_move`
    /// is set. Animators carry "last seen gen" and treat
    /// `pending_line_move_gen > last_seen` as a new event.
    pending_line_move_gen: u32,

    /// Per-visual-row band shape for the most recent line move. One entry
    /// per visual row of the moved block. Lives past the event observation
    /// because the renderer reads it on every frame of the trail flash;
    /// gets overwritten by the next move (or stays stale until then -- the
    /// rendering layer guards reads behind an active `LineMoveAnim`).
    line_move_bands: Vec<RowBand>,
}

